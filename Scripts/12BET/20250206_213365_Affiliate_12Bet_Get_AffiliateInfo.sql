	CREATE TABLE #FDM (AffId INT, Years INT, FDM INT)
		INSERT INTO #FDM (AffId, Years, FDM)
		SELECT mi.AffId, 
			YEAR(CreatedDate) AS Years,
			COUNT(1) AS FDM
		FROM dbo.MemberInfo mi WITH (NOLOCK)
			INNER JOIN #AffInfo a WITH(NOLOCK) ON a.AffId = mi.AffID
		WHERE mi.CreatedDate >= @FromDate AND mi.CreatedDate < DATEADD(DAY, 1, @ToDate)
			AND NOT EXISTS (
				SELECT 1 FROM dbo.MemberRemoval mr WITH (NOLOCK)
				WHERE mi.IBCCustID = mr.IBCCustID
					AND mr.RemovedDate >= @FromDate AND mr.RemovedDate < DATEADD(DAY, 1, @ToDate)
			)
		GROUP BY mi.AffId, YEAR(CreatedDate)

		 ;WITH CTE_WLData AS(
			SELECT Year(ac.MonthDate) AS Years
				,ac.AffId
				,SUM(ac.GrossWinloss) AS Winloss
				FROM dbo.rptAffCommission ac WITH (NOLOCK)
					INNER JOIN #AffInfo c ON c.AffId = ac.AffId
				WHERE ac.MonthDate >= @FromDate 
					AND ac.MonthDate < @ToDate
				GROUP BY Year(ac.MonthDate), ac.AffId
		 )
		SELECT y.Years
			,ai.STT
			,ai.AffId
			,ai.Username	
			,ISNULL(su.Signup, 0)			 AS Signups
			,ISNULL(fdm.FDM, 0)				 AS FDM
			,ISNULL(w.Winloss, 0)			 AS Winloss
		FROM #AffInfo ai
			CROSS JOIN (SELECT '2023' Years UNION ALL SELECT '2024')y
			LEFT JOIN #Signup su ON ai.AffId = su.AffId AND y.Years = su.Years
			LEFT JOIN #FDM fdm ON ai.AffId = fdm.AffId AND y.Years = fdm.Years
			LEFT JOIN CTE_WLData w  ON ai.AffId = w.AffId AND y.Years = w.Years
		ORDER by y.Years ASC, ai.STT ASC

