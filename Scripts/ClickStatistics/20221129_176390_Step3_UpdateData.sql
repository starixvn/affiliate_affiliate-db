DECLARE @BeginOfPerMonth SMALLDATETIME = @BeginRegenData
DECLARE @EndOfPerMonth  SMALLDATETIME, @LastDateSum SMALLDATETIME, @ClickID BIGINT

SELECT @ClickID = MIN(ClickID) FROM ClickStatistics1_bk WITH(NOLOCK) WHERE Date >= '2020-08-01'

--Update ClickStatistics1_bk
WHILE 1 = 1 
BEGIN
	UPDATE c
		SET c.Country = ctr.Code2
	FROM ClickStatistics1_bk c WITH(ROWLOCK, UPDLOCK)
		INNER JOIN #CountryCode ctr ON ctr.Code3 = c.Country
	WHERE c.ClickID >= @ClickID AND c.ClickID < @ClickID + 2000

	IF @@ROWCOUNT = 0
		BREAK

	SET @ClickID += 2000
END

